#menu driven calculator
fval=int(input('enter number'))
sval=int(input('enter number'))
oper=input('enter operation :')
if oper=='+':
    print(fval+sval)
elif oper=='-':
    print(fval-sval)
elif oper=='*':
    print(fval*sval)
elif oper=='/':
    print(fval/sval)
elif oper=='%':
    print(fval%sval)
else:
    print('no operatin you can write')
    


    

